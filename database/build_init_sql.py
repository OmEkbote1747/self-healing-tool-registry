"""Generate database/init_demo.sql from database/seed_data.py (deterministic).

    python -m database.build_init_sql          # rewrites database/init_demo.sql
    python -m database.build_init_sql --check  # exits 1 if the committed file is out of date

The SQL has three sections, marked so ADAPTIX can run them separately:
  -- @section schemas   creates the demo and sandbox schemas (skipped by the app if they already exist)
  -- @section logs      adaptix_experiments / adaptix_audit_log (never dropped by a reset)
  -- @section business  drops and recreates the business tables with the seed data (the reset)
"""
from __future__ import annotations

import sys
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

from database import seed_data as sd

OUT = Path(__file__).with_name("init_demo.sql")
S = "adaptix_demo"


def lit(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, Decimal)):
        return str(v)
    if isinstance(v, datetime):
        return "'" + v.isoformat() + "'"
    if isinstance(v, date):
        return "'" + v.isoformat() + "'"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table: str, rows: list[dict]) -> str:
    cols = list(rows[0])
    vals = ",\n  ".join("(" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)
    return f"INSERT INTO {S}.{table} ({', '.join(cols)}) VALUES\n  {vals};\n"


def build() -> str:
    orders, items = sd.orders_and_items()
    return f"""-- ADAPTIX demo database: schema, constraints and deterministic SYNTHETIC seed data.
-- Generated by `python -m database.build_init_sql` from database/seed_data.py - do not edit by hand.
-- All people, emails (example.com) and products are fictional. Safe to run more than once.
-- Run it in Neon's SQL Editor, or let the ADAPTIX app run it (Live Project Integration -> Set up / reset).
-- It only touches the {S} and {S}_sandbox schemas.

-- @section schemas
CREATE SCHEMA IF NOT EXISTS {S};
CREATE SCHEMA IF NOT EXISTS {S}_sandbox;

-- @section logs
CREATE TABLE IF NOT EXISTS {S}.adaptix_experiments (
  experiment_id     text PRIMARY KEY,
  scenario_name     text NOT NULL,
  selected_engine   text NOT NULL CHECK (selected_engine IN ('gemini', 'local')),
  injected_fault    text NOT NULL,
  status            text NOT NULL CHECK (status IN ('running', 'recovered', 'refused', 'failed', 'rolled_back',
                                                    'not_reproduced', 'blocked')),
  started_at        timestamptz NOT NULL DEFAULT now(),
  completed_at      timestamptz,
  recovery_ms       numeric(12,1),
  verified          boolean NOT NULL DEFAULT false,
  rollback_performed boolean NOT NULL DEFAULT false,
  error_details     text
);
CREATE TABLE IF NOT EXISTS {S}.adaptix_audit_log (
  audit_id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  experiment_id       text NOT NULL REFERENCES {S}.adaptix_experiments (experiment_id) ON DELETE CASCADE,
  event_type          text NOT NULL,
  event_time          timestamptz NOT NULL DEFAULT now(),
  details_json        jsonb NOT NULL DEFAULT '{{}}'::jsonb,
  patch_diff          text,
  validation_result   jsonb,
  verification_result jsonb
);
CREATE INDEX IF NOT EXISTS adaptix_audit_log_experiment_idx ON {S}.adaptix_audit_log (experiment_id, audit_id);
CREATE INDEX IF NOT EXISTS adaptix_experiments_started_idx ON {S}.adaptix_experiments (started_at);

-- @section business
DROP TABLE IF EXISTS {S}.inventory_events, {S}.order_items, {S}.orders, {S}.products, {S}.customers CASCADE;

CREATE TABLE {S}.customers (
  customer_id     text PRIMARY KEY CHECK (customer_id ~ '^C[0-9]{{3}}$'),
  full_name       text NOT NULL CHECK (length(full_name) BETWEEN 3 AND 120),
  email           text NOT NULL UNIQUE CHECK (email LIKE '%@example.com'),
  city            text NOT NULL,
  created_at      timestamptz NOT NULL,
  customer_status text NOT NULL CHECK (customer_status IN ('active', 'inactive', 'suspended'))
);
COMMENT ON COLUMN {S}.customers.customer_id IS 'Stable identifier of the customer (C001..)';

CREATE TABLE {S}.products (
  product_id     text PRIMARY KEY CHECK (product_id ~ '^P[0-9]{{3}}$'),
  product_name   text NOT NULL,
  category       text NOT NULL,
  unit_price     numeric(10,2) NOT NULL CHECK (unit_price > 0),
  stock_quantity integer NOT NULL CHECK (stock_quantity >= 0),
  is_active      boolean NOT NULL DEFAULT true
);

CREATE TABLE {S}.orders (
  order_id       text PRIMARY KEY CHECK (order_id ~ '^O[0-9]{{4}}$'),
  customer_id    text NOT NULL REFERENCES {S}.customers (customer_id),
  order_date     date NOT NULL,
  order_status   text NOT NULL CHECK (order_status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  total_amount   numeric(12,2) NOT NULL CHECK (total_amount >= 0),
  payment_method text NOT NULL CHECK (payment_method IN ('card', 'upi', 'netbanking', 'wallet', 'cod'))
);
COMMENT ON COLUMN {S}.orders.customer_id IS 'The customer who placed the order';
COMMENT ON COLUMN {S}.orders.order_status IS 'Lifecycle state of the order';
CREATE INDEX orders_customer_idx ON {S}.orders (customer_id, order_date);

CREATE TABLE {S}.order_items (
  item_id    integer PRIMARY KEY,
  order_id   text NOT NULL REFERENCES {S}.orders (order_id) ON DELETE CASCADE,
  product_id text NOT NULL REFERENCES {S}.products (product_id),
  quantity   integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
  line_total numeric(12,2) NOT NULL,
  CONSTRAINT line_total_matches CHECK (line_total = quantity * unit_price)
);
COMMENT ON COLUMN {S}.order_items.line_total IS 'quantity x unit_price for this line';
CREATE INDEX order_items_order_idx ON {S}.order_items (order_id);

CREATE TABLE {S}.inventory_events (
  event_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id      text NOT NULL REFERENCES {S}.products (product_id),
  event_type      text NOT NULL CHECK (event_type IN ('restock', 'sale', 'adjustment', 'return')),
  quantity_change integer NOT NULL CHECK (quantity_change <> 0),
  event_time      timestamptz NOT NULL DEFAULT now(),
  notes           text
);
CREATE INDEX inventory_events_product_idx ON {S}.inventory_events (product_id, event_time);

{insert("customers", sd.customers())}
{insert("products", sd.products())}
{insert("orders", orders)}
{insert("order_items", items)}
{insert("inventory_events", sd.inventory_events())}
SELECT setval(pg_get_serial_sequence('{S}.inventory_events', 'event_id'), (SELECT max(event_id) FROM {S}.inventory_events));
"""


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
